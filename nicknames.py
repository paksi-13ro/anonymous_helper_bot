import random

ADJECTIVES = [
    "Задумчивый", "Смелый", "Тихий", "Быстрый", "Мудрый",
    "Весёлый", "Загадочный", "Дерзкий", "Спокойный", "Яркий",
    "Хитрый", "Добрый", "Сонный", "Голодный", "Умный",
]
NOUNS = [
    "Пингвин", "Кот", "Лис", "Ёж", "Ворон",
    "Дельфин", "Тигр", "Сова", "Барсук", "Осьминог",
    "Кит", "Хамелеон", "Ёрш", "Бобр", "Мангуст",
]

def generate_nickname() -> str:
    return f"{random.choice(ADJECTIVES)} {random.choice(NOUNS)}"